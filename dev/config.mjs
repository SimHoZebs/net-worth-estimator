import { randomBytes, randomUUID } from 'node:crypto';
import { mkdir, open, readFile, rename, unlink, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { settingsFromEnv } from '../auth/casdoor/generate.mjs';

export const project = 'waypoint-dev';

export function tailnetOrigins(hostname) {
  const host = hostname.toLowerCase().replace(/\.$/, '');
  if (!/^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+ts\.net$/.test(host)) {
    throw new Error('Tailnet HTTPS requires this node\'s full ts.net DNS name');
  }
  return { APP_PUBLIC_URL: `https://${host}:5178`, CASDOOR_PUBLIC_URL: `https://${host}:8000` };
}

export function originProfile(appUrl, issuerUrl) {
  if (appUrl === 'http://localhost:5178' && issuerUrl === 'http://localhost:8000') return null;
  const app = new URL(appUrl);
  const expected = tailnetOrigins(app.hostname);
  if (appUrl !== expected.APP_PUBLIC_URL || issuerUrl !== expected.CASDOOR_PUBLIC_URL) {
    throw new Error('Dev origins must use localhost HTTP or matching tailnet HTTPS on ports 5178/8000');
  }
  return app.hostname;
}

export function newConfig(source = { container: 'net-worth-estimator' }, hostname) {
  const secret = () => randomBytes(24).toString('hex');
  return {
    version: 1, source, ownerSubject: null,
    identity: {
      CASDOOR_PUBLIC_URL: 'http://localhost:8000', APP_PUBLIC_URL: 'http://localhost:5178',
      AUTH_CLIENT_ID: 'waypoint-dev', AUTH_CLIENT_SECRET: secret(),
      CASDOOR_ADMIN_PASSWORD: secret(), CASDOOR_USER_NAME: 'household',
      CASDOOR_USER_PASSWORD: secret(), CASDOOR_USER_DISPLAY_NAME: 'Development owner',
      CASDOOR_BACKCHANNEL_LOGOUT_URL: 'http://backend:8787/v1/auth/backchannel-logout',
      ...(hostname ? tailnetOrigins(hostname) : {}),
    },
  };
}

export function settings(config) {
  if (config.version !== 1) throw new Error('Unsupported dev configuration version');
  if (config.ownerSubject !== undefined && config.ownerSubject !== null &&
    (typeof config.ownerSubject !== 'string' || !config.ownerSubject || config.ownerSubject !== config.ownerSubject.trim() || /[*,\r\n]/.test(config.ownerSubject))) {
    throw new Error('The primary plan owner must be one verified OIDC subject');
  }
  if (!config.source || (typeof config.source.file === 'string') === (typeof config.source.container === 'string')) {
    throw new Error('Configure exactly one snapshot source: file or container');
  }
  if ((config.source.file !== undefined && (typeof config.source.file !== 'string' || !config.source.file.startsWith('/'))) ||
    (config.source.container !== undefined && (typeof config.source.container !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9_.-]*$/.test(config.source.container)))) {
    throw new Error('Snapshot sources require an absolute file path or a Docker container name');
  }
  const result = settingsFromEnv(config.identity);
  originProfile(result.appUrl, result.publicUrl);
  return result;
}

export function composeEnvironment(config) {
  settings(config);
  return {
    DEV_UID: String(process.getuid()), DEV_GID: String(process.getgid()),
    DEV_APP_PUBLIC_URL: config.identity.APP_PUBLIC_URL,
    DEV_CASDOOR_PUBLIC_URL: config.identity.CASDOOR_PUBLIC_URL,
    DEV_AUTH_CLIENT_ID: config.identity.AUTH_CLIENT_ID,
    DEV_AUTH_CLIENT_SECRET: config.identity.AUTH_CLIENT_SECRET,
    DEV_OWNER_SUBJECT: config.ownerSubject ?? '',
  };
}

export async function writeComposeEnv(config, path) {
  const contents = '# Generated by scripts/dev setup from tmp/dev/config.json. Do not commit.\n' +
    Object.entries(composeEnvironment(config)).map(([name, value]) => `${name}='${value.replaceAll("'", "\\'")}'\n`).join('');
  try {
    if (await readFile(path, 'utf8') !== contents) throw new Error('Existing .env.dev differs from saved setup settings. Preserve it and reconcile the settings before setup.');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    await writeFile(path, contents, { mode: 0o600, flag: 'wx' });
  }
}

export async function saveConfig(stateDir, config) {
  settings(config);
  const path = resolve(stateDir, 'config.json');
  const temporary = `${path}.${randomUUID()}`;
  await writeFile(temporary, `${JSON.stringify(config, null, 2)}\n`, { mode: 0o600, flag: 'wx' });
  try { await rename(temporary, path); } finally { await unlink(temporary).catch((error) => { if (error.code !== 'ENOENT') throw error; }); }
}

export async function loadConfig(stateDir, create, source, hostname) {
  try {
    const config = JSON.parse(await readFile(resolve(stateDir, 'config.json'), 'utf8'));
    settings(config);
    if (hostname && config.identity.APP_PUBLIC_URL !== tailnetOrigins(hostname).APP_PUBLIC_URL) {
      throw new Error('Existing dev identities use another origin. Preserve their state and migrate the registered URLs before changing profiles. See dev/README.md.');
    }
    return config;
  } catch (error) {
    if (error.code !== 'ENOENT' || !create) throw error;
  }
  const config = newConfig(source, hostname);
  await saveConfig(stateDir, config);
  return config;
}

// One short-lived lock protects bootstrap and financial/sample snapshots.
// Compose owns service processes. This file never acts as a process manager.
export async function withLock(stateDir, action) {
  await mkdir(stateDir, { recursive: true, mode: 0o700 });
  const path = resolve(stateDir, 'operation.lock');
  let lock;
  for (let attempt = 0; attempt < 2; attempt++) {
    try { lock = await open(path, 'wx', 0o600); break; } catch (error) {
      if (error.code !== 'EEXIST') throw error;
      const pid = Number(await readFile(path, 'utf8'));
      let stale = false;
      if (Number.isInteger(pid) && pid > 0) {
        try { process.kill(pid, 0); } catch (probe) { stale = probe.code === 'ESRCH'; }
      }
      if (!stale) throw new Error('Another dev command is active.');
      await unlink(path);
    }
  }
  if (!lock) throw new Error('Could not acquire the dev operation lock');
  try { await lock.writeFile(String(process.pid)); return await action(); }
  finally { await lock.close(); await unlink(path); }
}
